// Generates the example-songs migration from lib/chart/examples.ts so the seeded
// charts are byte-for-byte the ones the tests round-trip.
// Run: npx tsx scripts/gen-seed.ts > supabase/migrations/20261112000100_seed_examples.sql
import { EXAMPLE_CHARTS } from "../lib/chart/examples";
import { getMeta, parseChart } from "../lib/chart";

const q = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);

const out = ["-- Example songs (marked is_example). Generated by scripts/gen-seed.ts.", ""];
for (const { slug, text } of EXAMPLE_CHARTS) {
  const meta = getMeta(parseChart(text).doc);
  out.push(`do $seed$
declare s_id uuid; r_id uuid;
begin
  insert into public.songs (slug, title, artist, key, bpm, time_sig, tags, status, is_example)
  values (${q(slug)}, ${q(meta.title)}, ${q(meta.artist)}, ${q(meta.key)}, ${meta.bpm ?? "null"}, ${q(meta.time)}, array[${meta.tags.map(q).join(", ")}]::text[], 'published', true)
  returning id into s_id;
  insert into public.revisions (song_id, chart_text, source, note)
  values (s_id, $chart$${text}$chart$, 'human', 'Example chart')
  returning id into r_id;
  update public.songs set current_revision_id = r_id where id = s_id;
end
$seed$;
`);
}
console.log(out.join("\n"));
